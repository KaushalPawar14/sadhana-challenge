// Regenerates schema.sql = base tables (as they exist live) + the structural migrations (000100-000300).
// 000400 (data migration of "Competition 1") is intentionally excluded: it only makes sense on a database
// that already holds the legacy single-competition data.
//   node scripts/build-schema.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const read = (p) => fs.readFileSync(p, 'utf8').split('\r\n').join('\n'); // tolerate CRLF checkouts
const baseline = read(path.join(root, 'scripts/db-tests/baseline.sql'));
const tables = [...baseline.matchAll(/^create table public\.(\w+) \((?:.|\n)*?\);$/gm)]
  .filter((m) => m[1] !== 'test_clock')
  .map((m) => m[0]);

const migDir = path.join(root, 'supabase/migrations');
const structural = fs.readdirSync(migDir).filter((f) => /^20261031000[1235]00_.*\.sql$/.test(f)).sort();

const out = [
  '-- =====================================================================',
  '-- schema.sql  -  FULL schema of the live project after the competition migrations.',
  '-- GENERATED by scripts/build-schema.mjs (do not edit by hand).',
  '-- A fresh Supabase project: run this whole file once in the SQL editor.',
  '-- Existing project: run supabase/migrations/*.sql in order instead (000400 migrates the legacy data).',
  '-- =====================================================================',
  '',
  '-- ---------- base tables (pre-competition shape, as found live) ----------',
  ...tables,
  '',
  "insert into public.app_settings (key, value) values",
  "  ('onboarding_fields', '[\"full_name\",\"mobile\",\"department\"]')",
  "on conflict (key) do nothing;",
  '',
];
for (const f of structural) {
  out.push(`-- ---------- supabase/migrations/${f} ----------`, read(path.join(migDir, f)), '');
}
fs.writeFileSync(path.join(root, 'schema.sql'), out.join('\n'));
console.log('schema.sql written:', tables.length, 'base tables +', structural.length, 'migrations');
